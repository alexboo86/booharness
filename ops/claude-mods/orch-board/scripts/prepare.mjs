import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { readFile, writeFile } from 'node:fs/promises';

// The mod sandbox only loads files inside its folder. Bundle the shared static
// registry, never hand-maintain a second set of SVG marks.
const target = new URL('../hooks/generated/family-logos.ts', import.meta.url);
const result = await build({
  absWorkingDir: fileURLToPath(new URL('../../../../', import.meta.url)),
  entryPoints: [fileURLToPath(new URL('../../../orchestrator/src/family-logos.ts', import.meta.url))],
  outfile: fileURLToPath(target),
  write: false,
  bundle: true,
  format: 'esm',
  banner: { js: '// Generated by node ops/claude-mods/orch-board/scripts/prepare.mjs; do not edit.\n// Source and licence details: ops/orchestrator/src/family-logos.ts' },
});
const output = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Family logo bundle is stale; run prepare.mjs');
  console.log('Family logo bundle matches the shared registry.');
} else {
  await writeFile(target, output);
  console.log('Prepared the family logo bundle from the shared registry.');
}
